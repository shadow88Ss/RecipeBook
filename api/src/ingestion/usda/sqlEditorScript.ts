// Layer 13B — the USDA ingestion as a self-contained SQL script for the
// Supabase SQL editor, for operators who cannot run the CLI (cli.ts) from a
// terminal (e.g. working from a phone).
//
// The script is generated from the same Plan (plan.ts, built from the
// official USDA file) and applies exactly the policy of apply.ts, in one
// transaction:
//   - a record already present with the same content hash is unchanged; only
//     its missing supplemental nutrients (nutrientMap.ts) are added;
//   - a record present with a different hash, or a Food name taken without
//     its source record, stops the whole script; nothing is written;
//   - absent records are inserted with alias, servings, nutrients and the
//     immutable food_source_record.
// DRY RUN is the default: the script does all checks and writes, then
// raises an error that rolls everything back and reports what WOULD be
// written. Changing `v_apply` to true commits.
//
//   npx tsx src/ingestion/usda/sqlEditorScript.ts --file <SR Legacy JSON> \
//     --release <file name> [--manifest <path>] [--supplement-only] --out <file.sql>

import { readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_MANIFEST } from './cli';
import { SUPPLEMENTAL_KEYS, USDA_NUTRIENT_MAP } from './nutrientMap';
import { buildPlan, SR_BASIS, USDA_LICENCE, type Plan } from './plan';

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** `supplementOnly`: every record must already be present; the script then
 * carries only the supplemental values (much smaller) and stops if any
 * record is missing. */
export function sqlEditorScript(plan: Plan, release: string, options: { supplementOnly?: boolean } = {}): string {
  const only = options.supplementOnly === true;
  if (!/^[A-Za-z0-9 ._:()-]{1,200}$/.test(release)) throw new Error('release must be 1-200 characters of letters, digits, space and ._:()-');
  const foods = plan.foods.map((f) => ({
    fdc: f.fdcId,
    ndb: f.ndbNumber,
    name: f.canonicalName,
    desc: f.description,
    cat: f.category,
    hash: f.contentSha256,
    ...(only ? {} : { srv: f.servings.map((s) => [s.description, s.grams]) }),
    nut: f.nutrients.filter((n) => !only || SUPPLEMENTAL_KEYS.has(n.key)).map((n) => [n.key, n.amount]),
  }));
  const units = USDA_NUTRIENT_MAP.map((m) => [m.key, m.unit]);
  const data = JSON.stringify({ foods, units, supplemental: [...SUPPLEMENTAL_KEYS], supplement_only: only });
  return `-- USDA FoodData Central SR Legacy ingestion: ${plan.manifestName} (${plan.foods.length} foods)${only ? ', supplemental nutrients only' : ''}
-- Generated by api/src/ingestion/usda/sqlEditorScript.ts from ${release}.
-- Same policy as the ingestion CLI. Nothing existing is updated or deleted.
-- STEP 1: run as is. It is a DRY RUN: it ends with an error that starts with
--         "DRY RUN" and says what would be written. Nothing is saved.
-- STEP 2: only if step 1 was as expected, edit the line just below
--         "declare" (v_apply) from false to true, and run again.
do $usda$
declare
  v_apply boolean := false;
  v_release text := ${quote(release)};
  v_data jsonb := ${quote(data)}::jsonb;
  v_food jsonb;
  v_hash text;
  v_food_id uuid;
  v_nut_id uuid;
  v_inserted int := 0;
  v_unchanged int := 0;
  v_supplemented int := 0;
  v_rows_food int := 0;
  v_rows_serving int := 0;
  v_rows_nutrient int := 0;
  v_n int;
  v_problems text[] := '{}';
  v_item jsonb;
begin
  -- The vocabulary must have every mapped nutrient, in the mapped unit.
  for v_item in select * from jsonb_array_elements(v_data->'units') loop
    if not exists (select 1 from nutrient where canonical_key = v_item->>0 and unit = v_item->>1) then
      v_problems := v_problems || ('nutrient ' || (v_item->>0) || ' missing or not in ' || (v_item->>1));
    end if;
  end loop;
  -- Changed records and name conflicts stop everything.
  for v_food in select * from jsonb_array_elements(v_data->'foods') loop
    select content_sha256 into v_hash from food_source_record where source_system = 'usda_fdc' and source_record_id = v_food->>'fdc';
    if found and v_hash <> v_food->>'hash' then
      v_problems := v_problems || ('CHANGED fdc ' || (v_food->>'fdc') || ' ' || (v_food->>'desc'));
    elsif not found and (v_data->>'supplement_only')::boolean then
      v_problems := v_problems || ('MISSING fdc ' || (v_food->>'fdc') || ' ' || (v_food->>'desc') || ' (this script only adds values to foods already loaded)');
    elsif not found and exists (select 1 from food where canonical_name = v_food->>'name') then
      v_problems := v_problems || ('CONFLICT fdc ' || (v_food->>'fdc') || ': a Food named ' || (v_food->>'name') || ' exists without its source record');
    end if;
  end loop;
  if cardinality(v_problems) > 0 then
    raise exception 'STOPPED, nothing written: %', array_to_string(v_problems, '; ');
  end if;

  for v_food in select * from jsonb_array_elements(v_data->'foods') loop
    select food_id into v_food_id from food_source_record where source_system = 'usda_fdc' and source_record_id = v_food->>'fdc';
    if found then
      v_unchanged := v_unchanged + 1;
      -- Supplemental nutrients only, and only where absent.
      insert into food_nutrient (food_id, nutrient_id, amount_per_canonical_unit, source, basis_quantity, basis_unit)
      select v_food_id, n.id, (x->>1)::numeric, 'trusted_database', ${SR_BASIS.quantity}, '${SR_BASIS.unit}'
        from jsonb_array_elements(v_food->'nut') x
        join nutrient n on n.canonical_key = x->>0
       where (v_data->'supplemental') ? (x->>0)
         and not exists (select 1 from food_nutrient e where e.food_id = v_food_id and e.nutrient_id = n.id);
      get diagnostics v_n = row_count;
      v_rows_nutrient := v_rows_nutrient + v_n;
      if v_n > 0 then v_supplemented := v_supplemented + 1; end if;
    else
      v_inserted := v_inserted + 1;
      insert into food (canonical_name, category, source) values (v_food->>'name', v_food->>'cat', 'trusted_database') returning id into v_food_id;
      v_rows_food := v_rows_food + 1;
      insert into food_alias (food_id, locale, alias_text, is_primary, source) values (v_food_id, 'en', v_food->>'desc', true, 'trusted_database');
      insert into food_serving (food_id, serving_description, region, canonical_quantity, canonical_unit, source)
      select v_food_id, x->>0, null, (x->>1)::numeric, 'g', 'trusted_database' from jsonb_array_elements(v_food->'srv') x;
      get diagnostics v_n = row_count;
      v_rows_serving := v_rows_serving + v_n;
      insert into food_nutrient (food_id, nutrient_id, amount_per_canonical_unit, source, basis_quantity, basis_unit)
      select v_food_id, n.id, (x->>1)::numeric, 'trusted_database', ${SR_BASIS.quantity}, '${SR_BASIS.unit}'
        from jsonb_array_elements(v_food->'nut') x join nutrient n on n.canonical_key = x->>0;
      get diagnostics v_n = row_count;
      v_rows_nutrient := v_rows_nutrient + v_n;
      insert into food_source_record (food_id, source_system, source_dataset, source_record_id, source_secondary_id, source_release, source_description, licence, content_sha256)
      values (v_food_id, 'usda_fdc', 'sr_legacy', v_food->>'fdc', v_food->>'ndb', v_release, v_food->>'desc', '${USDA_LICENCE}', v_food->>'hash');
    end if;
  end loop;

  if not v_apply then
    raise exception 'DRY RUN, nothing written. Would insert % new foods (% servings, % nutrient values in total incl. supplements); % already present and unchanged, % of them get supplemental values; 0 changed, 0 conflicts.',
      v_inserted, v_rows_serving, v_rows_nutrient, v_unchanged, v_supplemented;
  end if;
  raise notice 'APPLIED: % new foods, % servings, % nutrient values; % unchanged (% supplemented).', v_inserted, v_rows_serving, v_rows_nutrient, v_unchanged, v_supplemented;
end
$usda$;

-- After an applied run this shows the totals (a dry run stops before it).
select
  (select count(*) from food_source_record where source_system = 'usda_fdc') as usda_foods,
  (select count(*) from food_nutrient fn join nutrient n on n.id = fn.nutrient_id where n.canonical_key = 'total_sugars') as sugar_values,
  (select count(*) from food_nutrient fn join nutrient n on n.id = fn.nutrient_id where n.canonical_key = 'saturated_fat') as saturated_fat_values;
`;
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const get = (name: string) => {
    const i = argv.indexOf(`--${name}`);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const file = get('file');
  const release = get('release');
  const out = get('out');
  if (!file || !release || !out) throw new Error('Usage: sqlEditorScript.ts --file <SR Legacy JSON> --release <file name> [--manifest <path>] --out <file.sql>');
  const plan = buildPlan(JSON.parse(readFileSync(file, 'utf8')), JSON.parse(readFileSync(get('manifest') ?? DEFAULT_MANIFEST, 'utf8')));
  writeFileSync(out, sqlEditorScript(plan, release, { supplementOnly: argv.includes('--supplement-only') }));
  console.log(`wrote ${out}: ${plan.foods.length} foods`);
}
